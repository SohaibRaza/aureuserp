<?php

namespace App\Filament\Pages\Reports;

use BezhanSalleh\FilamentShield\Traits\HasPageShield;
use Filament\Actions\Action;
use Filament\Forms\Components\DatePicker;
use Filament\Forms\Components\Select;
use Filament\Forms\Concerns\InteractsWithForms;
use Filament\Forms\Contracts\HasForms;
use Filament\Pages\Page;
use Filament\Schemas\Components\Section;
use Illuminate\Support\Facades\DB;
use Livewire\Attributes\Computed;
use Webkul\Accounting\Filament\Clusters\Reporting;

/**
 * Custom report: Sales by Customer.
 *
 * Follows the plugin Reporting cluster pattern (see
 * plugins/webkul/accounting/src/Filament/Clusters/Reporting/Pages/*) but lives
 * in the app namespace so plugin updates never clobber it. Filament picks it
 * up automatically because it is attached to the Accounting Reporting cluster.
 *
 * URL:  /admin/accounting/reporting/sales-by-customer
 */
class SalesByCustomerReport extends Page implements HasForms
{
    use HasPageShield, InteractsWithForms;

    protected string $view = 'filament.pages.reports.sales-by-customer';

    protected static ?string $cluster = Reporting::class;

    protected static ?string $slug = 'sales-by-customer';

    protected static string|\BackedEnum|null $navigationIcon = 'heroicon-o-chart-bar';

    protected static ?int $navigationSort = 8;

    public ?array $data = [];

    protected static function getPagePermission(): ?string
    {
        // Name auto-generated by Filament Shield from the class FQCN.
        return 'page_filament_sales_by_customer_report';
    }

    public static function getNavigationLabel(): string
    {
        return 'Sales by Customer';
    }

    public function getTitle(): string
    {
        return 'Sales by Customer';
    }

    public static function getNavigationGroup(): string
    {
        return __('accounting::filament/clusters/reporting.pages.trial-balance.navigation.group');
    }

    public function mount(): void
    {
        $this->form->fill([
            'date_from' => now()->startOfYear()->toDateString(),
            'date_to'   => now()->toDateString(),
            'state'     => 'sale',
            'partner'   => null,
        ]);
    }

    protected function getFormSchema(): array
    {
        return [
            Section::make()
                ->columns([
                    'default' => 1,
                    'sm'      => 4,
                ])
                ->schema([
                    DatePicker::make('date_from')
                        ->label('From')
                        ->native(false)
                        ->suffixIcon('heroicon-o-calendar')
                        ->live(),

                    DatePicker::make('date_to')
                        ->label('To')
                        ->native(false)
                        ->suffixIcon('heroicon-o-calendar')
                        ->live(),

                    Select::make('state')
                        ->label('Order state')
                        ->options([
                            'sale'  => 'Sale orders',
                            'draft' => 'Quotations',
                            'sent'  => 'Quotations sent',
                            'all'   => 'All (incl. cancelled)',
                        ])
                        ->default('sale')
                        ->live(),

                    Select::make('partner')
                        ->label('Customer')
                        ->options(fn () => DB::table('partners_partners')->orderBy('name')->pluck('name', 'id'))
                        ->searchable()
                        ->placeholder('All customers')
                        ->live(),
                ])
                ->columnSpanFull(),
        ];
    }

    protected function getFormStatePath(): string
    {
        return 'data';
    }

    protected function getHeaderActions(): array
    {
        return [
            Action::make('export')
                ->label('Export CSV')
                ->icon('heroicon-o-arrow-down-tray')
                ->color('success')
                ->action(function () {
                    $data = $this->salesByCustomerData;

                    $csv = fopen('php://temp', 'r+');

                    fputcsv($csv, ['Customer', 'Orders', 'Total (untaxed)', 'Total']);

                    foreach ($data['rows'] as $row) {
                        fputcsv($csv, [
                            $row->customer,
                            $row->orders,
                            number_format((float) $row->total_untaxed, 2, '.', ''),
                            number_format((float) $row->total, 2, '.', ''),
                        ]);
                    }

                    fputcsv($csv, ['TOTAL', $data['totals']['orders'], $data['totals']['untaxed'], $data['totals']['grand']]);

                    rewind($csv);

                    $contents = stream_get_contents($csv);

                    return response()->streamDownload(
                        function () use ($contents) {
                            echo $contents;
                        },
                        'sales-by-customer-'.$data['date_to'].'.csv'
                    );
                }),
        ];
    }

    #[Computed]
    public function salesByCustomerData(): array
    {
        $state = $this->form->getState();

        $dateFrom = $state['date_from'] ?? now()->startOfYear()->toDateString();
        $dateTo = $state['date_to'] ?? now()->toDateString();
        $stateFilter = $state['state'] ?? 'sale';
        $partnerId = $state['partner'] ?? null;

        $query = DB::table('sales_orders')
            ->join('partners_partners', 'sales_orders.partner_id', '=', 'partners_partners.id')
            ->selectRaw('
                partners_partners.id   AS partner_id,
                partners_partners.name AS customer,
                COUNT(*)               AS orders,
                COALESCE(SUM(sales_orders.amount_untaxed), 0) AS total_untaxed,
                COALESCE(SUM(sales_orders.amount_total), 0)   AS total
            ')
            ->whereBetween('sales_orders.date_order', [$dateFrom, $dateTo])
            ->groupBy('partners_partners.id', 'partners_partners.name')
            ->orderByDesc('total');

        if ($stateFilter !== 'all') {
            $query->where('sales_orders.state', $stateFilter);
        }

        if (! empty($partnerId)) {
            $query->where('sales_orders.partner_id', $partnerId);
        }

        $rows = $query->get();

        return [
            'rows'      => $rows,
            'date_from' => $dateFrom,
            'date_to'   => $dateTo,
            'totals'    => [
                'orders'  => $rows->sum('orders'),
                'untaxed' => number_format((float) $rows->sum('total_untaxed'), 2),
                'grand'   => number_format((float) $rows->sum('total'), 2),
            ],
        ];
    }
}

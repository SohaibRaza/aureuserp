<?php

namespace App\Filament\Pages\Reports;

use BezhanSalleh\FilamentShield\Traits\HasPageShield;
use Filament\Actions\Action;
use Filament\Forms\Components\DatePicker;
use Filament\Forms\Components\Select;
use Filament\Forms\Concerns\InteractsWithForms;
use Filament\Forms\Contracts\HasForms;
use Filament\Pages\Page;
use Filament\Schemas\Components\Section;
use Illuminate\Support\Facades\DB;
use Livewire\Attributes\Computed;
use Webkul\Accounting\Filament\Clusters\Reporting;

/**
 * Custom report: Sales by Product.
 *
 * Mirrors SalesByCustomerReport (same Reporting cluster, same filter
 * conventions, same CSV export) but aggregates sales_order_lines by product.
 * Lives in the app namespace so plugin updates never clobber it.
 *
 * URL:  /admin/accounting/reporting/sales-by-product
 */
class SalesByProductReport extends Page implements HasForms
{
    use HasPageShield, InteractsWithForms;

    protected string $view = 'filament.pages.reports.sales-by-product';

    protected static ?string $cluster = Reporting::class;

    protected static ?string $slug = 'sales-by-product';

    protected static string|\BackedEnum|null $navigationIcon = 'heroicon-o-cube';

    protected static ?int $navigationSort = 9;

    public ?array $data = [];

    protected static function getPagePermission(): ?string
    {
        // Name auto-generated by Filament Shield from the class FQCN.
        return 'page_filament_sales_by_product_report';
    }

    public static function getNavigationLabel(): string
    {
        return 'Sales by Product';
    }

    public function getTitle(): string
    {
        return 'Sales by Product';
    }

    public static function getNavigationGroup(): string
    {
        return __('accounting::filament/clusters/reporting.pages.trial-balance.navigation.group');
    }

    public function mount(): void
    {
        $this->form->fill([
            'date_from' => now()->startOfYear()->toDateString(),
            'date_to'   => now()->toDateString(),
            'state'     => 'sale',
            'product'   => null,
            'category'  => null,
        ]);
    }

    protected function getFormSchema(): array
    {
        return [
            Section::make()
                ->columns([
                    'default' => 1,
                    'sm'      => 5,
                ])
                ->schema([
                    DatePicker::make('date_from')
                        ->label('From')
                        ->native(false)
                        ->suffixIcon('heroicon-o-calendar')
                        ->live(),

                    DatePicker::make('date_to')
                        ->label('To')
                        ->native(false)
                        ->suffixIcon('heroicon-o-calendar')
                        ->live(),

                    Select::make('state')
                        ->label('Order state')
                        ->options([
                            'sale'  => 'Sale orders',
                            'draft' => 'Quotations',
                            'sent'  => 'Quotations sent',
                            'all'   => 'All (incl. cancelled)',
                        ])
                        ->default('sale')
                        ->live(),

                    Select::make('product')
                        ->label('Product')
                        ->options(fn () => DB::table('products_products')->orderBy('name')->pluck('name', 'id'))
                        ->searchable()
                        ->placeholder('All products')
                        ->live(),

                    Select::make('category')
                        ->label('Category')
                        ->options(fn () => DB::table('products_categories')->orderBy('name')->pluck('name', 'id'))
                        ->searchable()
                        ->placeholder('All categories')
                        ->live(),
                ])
                ->columnSpanFull(),
        ];
    }

    protected function getFormStatePath(): string
    {
        return 'data';
    }

    protected function getHeaderActions(): array
    {
        return [
            Action::make('export')
                ->label('Export CSV')
                ->icon('heroicon-o-arrow-down-tray')
                ->color('success')
                ->action(function () {
                    $data = $this->salesByProductData;

                    $csv = fopen('php://temp', 'r+');

                    fputcsv($csv, ['Product', 'Orders', 'Qty', 'Total (untaxed)', 'Total']);

                    foreach ($data['rows'] as $row) {
                        fputcsv($csv, [
                            $row->product,
                            $row->orders,
                            rtrim(rtrim(number_format((float) $row->qty, 2, '.', ''), '0'), '.'),
                            number_format((float) $row->untaxed, 2, '.', ''),
                            number_format((float) $row->total, 2, '.', ''),
                        ]);
                    }

                    fputcsv($csv, ['TOTAL', $data['totals']['orders'], $data['totals']['qty'], $data['totals']['untaxed'], $data['totals']['grand']]);

                    rewind($csv);

                    $contents = stream_get_contents($csv);

                    return response()->streamDownload(
                        function () use ($contents) {
                            echo $contents;
                        },
                        'sales-by-product-'.$data['date_to'].'.csv'
                    );
                }),
        ];
    }

    #[Computed]
    public function salesByProductData(): array
    {
        $state = $this->form->getState();

        $dateFrom = $state['date_from'] ?? now()->startOfYear()->toDateString();
        $dateTo = $state['date_to'] ?? now()->toDateString();
        $stateFilter = $state['state'] ?? 'sale';
        $productId = $state['product'] ?? null;
        $categoryId = $state['category'] ?? null;

        $query = DB::table('sales_order_lines as l')
            ->join('sales_orders as o', 'l.order_id', '=', 'o.id')
            ->join('products_products as p', 'l.product_id', '=', 'p.id')
            ->leftJoin('products_categories as pc', 'p.category_id', '=', 'pc.id')
            ->selectRaw('
                p.id        AS product_id,
                p.name      AS product,
                pc.name     AS category,
                COUNT(DISTINCT o.id)                    AS orders,
                COALESCE(SUM(l.product_qty), 0)         AS qty,
                COALESCE(SUM(l.price_subtotal), 0)      AS untaxed,
                COALESCE(SUM(l.price_total), 0)         AS total
            ')
            ->whereBetween('o.date_order', [$dateFrom, $dateTo])
            ->groupBy('p.id', 'p.name', 'pc.name')
            ->orderByDesc('total');

        if ($stateFilter !== 'all') {
            $query->where('o.state', $stateFilter);
        }

        if (! empty($productId)) {
            $query->where('p.id', $productId);
        }

        if (! empty($categoryId)) {
            $query->where('p.category_id', $categoryId);
        }

        $rows = $query->get();

        return [
            'rows'      => $rows,
            'date_from' => $dateFrom,
            'date_to'   => $dateTo,
            'totals'    => [
                'orders'  => $rows->sum('orders'),
                'qty'     => rtrim(rtrim(number_format((float) $rows->sum('qty'), 2, '.', ''), '0'), '.'),
                'untaxed' => number_format((float) $rows->sum('untaxed'), 2),
                'grand'   => number_format((float) $rows->sum('total'), 2),
            ],
        ];
    }
}

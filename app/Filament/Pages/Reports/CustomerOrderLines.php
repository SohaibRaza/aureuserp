<?php

namespace App\Filament\Pages\Reports;

use BezhanSalleh\FilamentShield\Traits\HasPageShield;
use Filament\Actions\Action;
use Filament\Forms\Components\DatePicker;
use Filament\Forms\Concerns\InteractsWithForms;
use Filament\Forms\Contracts\HasForms;
use Filament\Pages\Page;
use Filament\Schemas\Components\Section;
use Illuminate\Support\Facades\DB;
use Livewire\Attributes\Computed;
use Livewire\Attributes\Url;
use Webkul\Accounting\Filament\Clusters\Reporting;

/**
 * Drill-down for the Sales by Customer report: every order line of one
 * customer in the chosen period, grouped by order.
 *
 * Reached from SalesByCustomerReport by clicking a customer row.
 * URL: /admin/accounting/reporting/customer-order-lines?partner=ID&from=...&to=...&state=...
 */
class CustomerOrderLines extends Page implements HasForms
{
    use HasPageShield, InteractsWithForms;

    protected string $view = 'filament.pages.reports.customer-order-lines';

    protected static ?string $cluster = Reporting::class;

    protected static ?string $slug = 'customer-order-lines';

    protected static string|\BackedEnum|null $navigationIcon = 'heroicon-o-chart-bar';

    protected static bool $shouldRegisterNavigation = false;

    public ?array $data = [];

    #[Url]
    public ?int $partner = null;

    #[Url]
    public ?string $from = null;

    #[Url]
    public ?string $to = null;

    #[Url]
    public string $state = 'sale';

    public function mount(): void
    {
        $this->from ??= now()->startOfYear()->toDateString();
        $this->to ??= now()->toDateString();

        $this->form->fill([
            'from' => $this->from,
            'to'   => $this->to,
        ]);
    }

    protected static function getPagePermission(): ?string
    {
        // Name auto-generated by Filament Shield from the class FQCN.
        return 'page_filament_customer_order_lines';
    }

    public static function getNavigationLabel(): string
    {
        return 'Customer Order Lines';
    }

    public function getTitle(): string
    {
        return ($this->customerName ?? 'Customer').' — Order Lines';
    }

    #[Computed]
    public function customerName(): ?string
    {
        return DB::table('partners_partners')->where('id', $this->partner)->value('name');
    }

    protected function getFormSchema(): array
    {
        return [
            Section::make()
                ->columns([
                    'default' => 1,
                    'sm'      => 2,
                ])
                ->schema([
                    DatePicker::make('from')
                        ->label('From')
                        ->native(false)
                        ->suffixIcon('heroicon-o-calendar')
                        ->live()
                        ->afterStateUpdated(fn ($state) => $this->from = $state),

                    DatePicker::make('to')
                        ->label('To')
                        ->native(false)
                        ->suffixIcon('heroicon-o-calendar')
                        ->live()
                        ->afterStateUpdated(fn ($state) => $this->to = $state),
                ])
                ->columnSpanFull(),
        ];
    }

    protected function getFormStatePath(): string
    {
        return 'data';
    }

    protected function getHeaderActions(): array
    {
        return [
            Action::make('back')
                ->label('Back to Sales by Customer')
                ->icon('heroicon-o-arrow-left')
                ->color('gray')
                ->url(SalesByCustomerReport::getUrl()),
        ];
    }

    protected function orderStateFilter(): array
    {
        // Dates may have been re-picked in the form (d/m/Y strings from the picker).
        $from = $this->normalizeDate($this->from);
        $to = $this->normalizeDate($this->to);

        return [$from, $to];
    }

    protected function normalizeDate(?string $date): string
    {
        if (preg_match('/^(\d{2})\/(\d{2})\/(\d{4})$/', (string) $date, $m)) {
            return "{$m[3]}-{$m[2]}-{$m[1]}";
        }

        return $date ?: now()->toDateString();
    }

    #[Computed]
    public function linesData(): array
    {
        if (! $this->partner) {
            return ['orders' => [], 'kpis' => ['orders' => 0, 'qty' => 0, 'untaxed' => '0.00', 'total' => '0.00']];
        }

        [$from, $to] = $this->orderStateFilter();

        $query = DB::table('sales_order_lines as l')
            ->join('sales_orders as o', 'l.order_id', '=', 'o.id')
            ->leftJoin('products_products as p', 'l.product_id', '=', 'p.id')
            ->where('o.partner_id', $this->partner)
            ->whereBetween('o.date_order', [$from, $to])
            ->whereNull('l.display_type')
            ->selectRaw("
                o.id AS order_id, o.name AS order_name, o.date_order, o.state,
                l.id AS line_id, l.name AS description, l.product_qty, l.qty_delivered, l.qty_invoiced,
                l.price_unit, l.price_subtotal, l.price_total,
                COALESCE(p.name, split_part(l.name, E'\n', 1)) AS product_name
            ")
            ->orderByDesc('o.date_order')
            ->orderBy('o.id')
            ->orderBy('l.id');

        if ($this->state !== 'all') {
            $query->where('o.state', $this->state);
        }

        $rows = $query->get();

        $orders = [];

        foreach ($rows as $row) {
            $orders[$row->order_id]['header'] ??= [
                'name'      => $row->order_name,
                'date'      => $row->date_order,
                'state'     => $row->state,
                'untaxed'   => 0.0,
                'total'     => 0.0,
            ];

            $orders[$row->order_id]['lines'][] = $row;
            $orders[$row->order_id]['header']['untaxed'] += (float) $row->price_subtotal;
            $orders[$row->order_id]['header']['total'] += (float) $row->price_total;
        }

        return [
            'orders' => $orders,
            'kpis'   => [
                'orders'  => count($orders),
                'qty'     => (float) $rows->sum('product_qty'),
                'untaxed' => number_format((float) $rows->sum('price_subtotal'), 2),
                'total'   => number_format((float) $rows->sum('price_total'), 2),
            ],
        ];
    }
}
